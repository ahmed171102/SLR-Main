    "                        if tracked_label == \"space\":\n",
    "                            if not predicted_sentence.endswith(\" \"):\n",
    "                                predicted_sentence += \" \"\n",
    "                        elif tracked_label == \"del\":\n",
    "                            if predicted_sentence:\n",
