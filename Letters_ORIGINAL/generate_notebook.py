    "                    elif status == \"cooldown\":\n",
    "                        display_status = f\"{tracked_label} ({tracked_conf:.0%}) ✓ Committed - change sign\"\n",
    "                        status_color = (255, 200, 0)\n",
    "                    elif status == \"committed\":\n",
